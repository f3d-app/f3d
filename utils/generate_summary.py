import json
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from argparse import ArgumentParser
from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Self
from PIL import Image, ImageChops


def main():
    parser = ArgumentParser()
    parser.add_argument(
        "junit_xml",
        type=Path,
        help="JUnit XML file generated by ctest --output-junit",
    )

    parser.add_argument(
        "--source_dir",
        type=Path,
        required=True,
        help="Path to the source directory",
    )

    parser.add_argument(
        "--build_dir",
        type=Path,
        required=True,
        help="Path to the build directory",
    )

    parser.add_argument(
        "--upload",
        action="store_true",
        help="upload images instead of printing them locally",
    )

    # The token is not needed at the moment because authentication is not required
    # for sending images to the server
    parser.add_argument(
        "--token",
        help="token used to send images to the server",
    )
    args = parser.parse_args()

    if not args.junit_xml.is_file():
        print(f"{str(args.junit_xml)!r} is not a file")
        sys.exit(1)

    root = ET.parse(args.junit_xml).getroot()
    failed_tests = list(
        FailedTest.from_junit_xml(root, args.source_dir, args.build_dir)
    )

    print_summary(root, failed_tests, args.token, args.upload)


@dataclass
class FailedTest:
    name: str
    """name of the failed test"""
    log: str
    """log output of the failed test"""
    images: list[tuple[Path, Path]]
    """pairs of (output, reference) images"""
    labels: list[str]
    """labels associated with the failed test"""
    error: str
    """error message associated with the failed test"""

    @classmethod
    def from_junit_xml(
        cls, root: ET.Element, source_dir: Path, build_dir: Path
    ) -> Iterator[Self]:
        for testcase in root.iter("testcase"):
            failure = testcase.find("failure")
            if failure is None:
                continue

            error = failure.get("message", "")

            name = testcase.get("name", "").rpartition("::")[2]
            log = testcase.findtext("system-out", default="")

            # labels are stored as a ";" separated list in the "cmake_labels" property
            labels: list[str] = []
            prop = testcase.find("properties/property[@name='cmake_labels']")
            if prop is not None:
                labels = prop.get("value", "").split(";")

            # SDK tests use TestSDKHelpers.h to print a multi-line summary so we need to track a
            # "Current rendering difference ..." line before a "Result image saved ..." line
            images: list[tuple[Path, Path]] = []
            reference = None
            for line in log.splitlines():
                if m := re.match(
                    r"Current rendering difference with reference image (.+) :", line
                ):
                    reference = Path(m.group(1))
                elif reference and (m := re.match(r"Result image saved to (.+)", line)):
                    images.append((Path(m.group(1)), reference))
                    reference = None

            # other tests (the f3d application ones) do not log paths, so rely on the naming
            # convention of the test, as the junit output does not contain the command line
            if not images:
                images.append(
                    (
                        build_dir.resolve() / "Testing/Temporary" / f"{name}.png",
                        source_dir.resolve() / "testing/baselines" / f"{name}.png",
                    )
                )

            yield cls(name, log, images, labels, error)


def print_table(headers: list[str], cells: list[str]):
    widths = [max(len(h), len(c)) for h, c in zip(headers, cells)]
    print("| " + " | ".join(h.center(w) for h, w in zip(headers, widths)) + " |")
    print("|" + "|".join("-" * (w + 2) for w in widths) + "|")
    print("| " + " | ".join(c.center(w) for c, w in zip(cells, widths)) + " |")
    print()


def print_summary(
    root: ET.Element,
    failed_tests: Iterable[FailedTest],
    token: str | None,
    upload: bool,
):
    tests = int(root.get("tests", 0))
    disabled = int(root.get("disabled", 0))
    failures = int(root.get("failures", 0))
    passed = tests - disabled - failures
    seconds = round(float(root.get("time", 0)))
    duration = f"{seconds // 60}m {seconds % 60:02d}s"

    print_table(
        [
            ":test_tube: Total",
            ":white_check_mark: Passed",
            ":x: Failed",
            ":next_track_button: Disabled",
            ":stopwatch: Time",
        ],
        [str(tests), str(passed), str(failures), str(disabled), duration],
    )

    if not failed_tests:
        return

    print("### :mag: Failing tests:\n")
    for test in failed_tests:
        # ctest replaces characters that are invalid in XML (ANSI escapes, other control
        # characters) with a "[NON-XML-CHAR-0x..]" placeholder, restore them
        log = re.sub(
            r"\[NON-XML-CHAR-0x([0-9A-Fa-f]+)\]",
            lambda m: chr(int(m.group(1), 16)),
            test.log,
        ).strip()
        print("<details>")
        print(f"  <summary>{test.name} ({test.error})</summary>\n")

        if test.labels:
            test.labels = [f"`{label}`" for label in test.labels]
            print(" ".join(test.labels) + "\n")

        for output, reference in test.images:
            if output.is_file() and reference.is_file():
                img1 = Image.open(reference).convert("RGB")
                img2 = Image.open(output).convert("RGB")

                diff = ImageChops.difference(img1, img2)
                diffName = output.parent / Path(output.stem + ".diff.png")
                diff.save(diffName)
                baseline = image_markdown(reference, token, upload)
                result = image_markdown(output, token, upload)
                diff_img = image_markdown(diffName, token, upload)
                print("#### Images")
                print_table(
                    ["Baseline", "Output", "Diff"], [baseline, result, diff_img]
                )
        print("#### Log")
        print(f"```\n{log}\n```")
        print("</details>\n")


def image_markdown(image: Path, token: str | None, upload: bool):
    if image.is_file():

        if not upload:
            return f"![]({image})"

        url = "https://server.f3d.app/upload"

        headers = {
            "Content-Type": "image/png",
        }

        if token:
            headers["Authorization"] = f"Bearer {token}"

        request = urllib.request.Request(
            url,
            data=image.read_bytes(),
            headers=headers,
            method="POST",
        )

        try:
            with urllib.request.urlopen(request) as response:
                result = json.loads(response.read())

            try:
                if not result.get("success"):
                    return "_upload failed (server error)_"
            except AttributeError:
                return "_upload failed (unexpected response)_"

            return f"![](https://server.f3d.app/upload/{result['sha256']})"
        except urllib.error.HTTPError as e:
            return f"_upload failed ({e.reason})_"
    return "_missing_"


if __name__ == "__main__":
    sys.exit(main())
